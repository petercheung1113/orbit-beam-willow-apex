export const FAQ_PER_UNIT = 10000;

export type Guide = { q: string; steps: string[] };

type Maker = {
  keys: string[];
  build: (n: number, nums: number[]) => Guide;
};

function maker(keys: string[], question: (n: number, nums: number[]) => string, steps: string[]): Maker {
  return { keys, build: (n, nums) => ({ q: question(n, nums), steps }) };
}

function aOf(n: number, nums: number[], salt = 0) {
  return nums[0] ?? 2 + n + salt;
}

function bOf(n: number, nums: number[]) {
  return nums[1] ?? 2 + (n % 9);
}

function cOf(n: number, nums: number[]) {
  return nums[2] ?? 3 + (n % 7);
}

function divisors(n: number) {
  return [10, 100, 1000, 0.1, 0.01, 0.001][n % 6]!;
}

