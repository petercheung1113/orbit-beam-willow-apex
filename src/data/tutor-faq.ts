function makersOf(unitId: string) {
  return BANK[unitId] ?? BANK["6N1"]!;
}

export function faqAt(unitId: string, index: number): Guide {
  const makers = makersOf(unitId);
  const i = ((index % FAQ_PER_UNIT) + FAQ_PER_UNIT) % FAQ_PER_UNIT;
  const guide = makers[i % makers.length]!.build(Math.floor(i / makers.length), []);
  return { ...guide, q: `學生${i + 1}問：${guide.q}` };
}

export function guideFor(unitId: string, message: string): Guide {
  const makers = makersOf(unitId);
  const compact = message.replace(/\s+/g, "");
  const nums = (message.match(/\d+(?:\.\d+)?/g) ?? []).map(Number).filter((n) => Number.isFinite(n));
  let best = makers[0]!;
  let score = -1;
  makers.forEach((item, index) => {
    const hit = item.keys.reduce((sum, key) => sum + (compact.includes(key.replace(/\s+/g, "")) ? 1 : 0), 0);
    const rank = hit * 20 - index;
    if (rank > score) {
      score = rank;
      best = item;
    }
  });
  const n = nums.length ? Math.abs(Math.round(nums[0]! * 10)) % FAQ_PER_UNIT : 0;
  return best.build(n, nums);
}

export function speakGuide(guide: Guide): string {
  return ["我不會直接告訴你答案。跟着下面的步驟自己找。", "", ...guide.steps.map((step, index) => `${index + 1}. ${step}`), "", "你先做第 1 步，把你的想法打給我。"].join("\n");
}
